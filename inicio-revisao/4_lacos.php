<?php

// laço (for) para tabuada do 8
for ($i = 1; $i <= 10; $i++) {
    echo "8 x $i = " . (8 * $i) . "</n>";
}

// while -(enquanto) contagem regressiva
echo "</n>";
$n = 5;
while ($n >0) {
echo $n. "</n>";
$n--; 
}

// Do while - (faça enquanto) executa ao menos 1 vez
$x = 10;
do {
    echo "x vale: $x";
    $x++;
} while ($x <= 10);


